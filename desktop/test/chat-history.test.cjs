const test = require('node:test')
const assert = require('node:assert/strict')
const { ChatHistory } = require('../src/chat-history.js')

test('history retains the latest 50 messages separately per account and restores drafts', () => {
  const history = new ChatHistory()
  for (let i = 0; i < 55; i++) history.add('a', String(i))
  history.add('b', 'other')
  assert.equal(history.navigate('a', 'up', 'draft'), '54')
  for (let i = 0; i < 100; i++) history.navigate('a', 'up', '')
  assert.equal(history.navigate('a', 'up', ''), '5')
  assert.equal(history.navigate('b', 'up', ''), 'other')
  for (let i = 0; i < 50; i++) history.navigate('a', 'down', '')
  assert.equal(history.navigate('a', 'down', ''), 'draft')
  history.navigate('a', 'up', '')
  history.reset('a')
  assert.equal(history.navigate('a', 'up', 'new draft'), '54')
  assert.equal(history.navigate('a', 'down', ''), 'new draft')
})
