'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { setup } = require('../test-fixtures/bedrock/phase2-harness.cjs')
const flush = () => new Promise(setImmediate)
const item = (id, count, stack_id) => ({ network_id: id, count, stack_id, has_stack_id: 1 })
test('Bedrock auto deposit opens the configured target and deposits unlocked stacks', async () => {
  const h = setup({ autoDepositToChest: true, bedrockDepositTarget: { x: 1, y: 65, z: 4 }, lockedInventorySlots: [37] })
  h.client.emit('inventory_content', { window_id: 0, input: [item(1, 5, 10), item(2, 3, 20)] })
  h.timers.advance(0); await flush()
  const packet = h.packets('inventory_transaction')[0]
  assert.equal(packet.transaction.transaction_data.action_type, 'click_block')
  assert.deepEqual(packet.transaction.transaction_data.block_position, { x: 1, y: 65, z: 4 })
  const { createSerializer } = require('bedrock-protocol/src/transforms/serializer')
  assert.doesNotThrow(() => createSerializer(h.client.version).createPacketBuffer({ name: 'inventory_transaction', params: packet }))
  h.client.emit('container_open', { window_id: 5, window_type: 'container' })
  h.client.emit('inventory_content', { window_id: 5, input: [{ network_id: 0 }] })
  h.timers.advance(100); await flush()
  assert.equal(h.packets('item_stack_request').length, 1)
  h.client.emit('item_stack_response', { responses: [{ request_id: -1, status: 'ok', containers: [] }] }); await flush()
  assert.equal(h.packets('container_close').length, 1)
  assert.equal(h.session.rawInventory[1].count, 3)
  h.manager.disconnect('phase2')
})
test('Bedrock auto deposit reports missing window and distant target', async () => {
  const h = setup({ autoDepositToChest: true, bedrockDepositTarget: { x: 1, y: 65, z: 4 } })
  h.client.emit('inventory_content', { window_id: 0, input: [item(1, 5, 10)] })
  h.timers.advance(0)
  for (let i = 0; i < 50; i++) { h.timers.advance(100); await flush() }
  assert.match(h.events.filter(e => e[0] === 'log').at(-1)[2].message, /No container window opened/)
  h.session.account.bedrockDepositTarget = { x: 100, y: 65, z: 4 }
  await assert.rejects(h.manager.autoDeposit('phase2', h.session), /out of reach/)
  h.manager.disconnect('phase2')
})
test('Bedrock deposit walks toward a nearby target and releases movement when disabled', async () => {
  const h = setup({ autoDepositToChest: true, bedrockDepositTarget: { x: 1, y: 65, z: 10 } })
  h.client.emit('inventory_content', { window_id: 0, input: [item(1, 5, 10)] })
  h.timers.advance(0); assert.deepEqual(h.manager.inputOwners('phase2', 'forward'), ['autoDeposit'])
  h.timers.advance(1000); await flush()
  assert.ok(h.session.position.z > 3.4567)
  h.manager.setAutoDeposit('phase2', false)
  assert.deepEqual(h.manager.inputOwners('phase2', 'forward'), [])
  h.timers.advance(100); await flush()
  assert.equal(h.packets('inventory_transaction').length, 0)
  h.manager.disconnect('phase2')
})
test('Bedrock deposit honors interval and full triggers', async () => {
  const h = setup({ autoDepositToChest: true, autoDepositMode: 'interval', autoDepositInterval: 300, bedrockDepositTarget: { x: 1, y: 65, z: 4 } })
  h.client.emit('inventory_content', { window_id: 0, input: [item(1, 5, 10)] })
  h.timers.advance(0); await flush(); assert.equal(h.packets('inventory_transaction').length, 0)
  h.manager.setAutoDeposit('phase2', true, 5, { ...h.session.account, autoDepositMode: 'inventoryFull', autoDepositFullThreshold: 0 })
  h.timers.advance(0); await flush(); assert.equal(h.packets('inventory_transaction').length, 0)
  h.manager.setAutoDeposit('phase2', true, 5, { ...h.session.account, autoDepositFullThreshold: 35 })
  h.timers.advance(0); await flush(); assert.equal(h.packets('inventory_transaction').length, 1)
  h.manager.disconnect('phase2')
})
