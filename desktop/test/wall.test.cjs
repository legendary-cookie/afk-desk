const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { liveIds } = require('../src/wall.js')
const { AppCore } = require('../core/app-core.cjs')

test('wall selects only the bounded number of live feeds', () => {
  const accounts = Array.from({ length: 15 }, (_, i) => ({ id: String(i) }))
  assert.deepEqual(liveIds(accounts), ['0', '1', '2', '3'])
  assert.deepEqual(liveIds(accounts, 0), [])
  assert.equal(liveIds(accounts, 100).length, 12)
  assert.deepEqual(liveIds(accounts, 2), ['0', '1'])
})

test('wall settings are bounded, persisted and survive partial saves', t => {
  const userDataPath = fs.mkdtempSync(path.join(os.tmpdir(), 'wall-settings-'))
  t.after(() => fs.rmSync(userDataPath, { recursive: true, force: true }))
  const core = new AppCore({ userDataPath })
  assert.equal(core.settings.get().wallFps, 1)
  assert.equal(core.settings.get().wallMaxLive, 4)
  core.settings.save({ wallFps: 9, wallMaxLive: 50 })
  assert.equal(core.settings.get().wallFps, 5)
  assert.equal(core.settings.get().wallMaxLive, 12)
  core.settings.save({ wallFps: 0.1, wallMaxLive: 0 })
  core.settings.save({ povRenderDistance: 2 })
  assert.equal(new AppCore({ userDataPath }).settings.get().wallFps, 0.2)
  assert.equal(new AppCore({ userDataPath }).settings.get().wallMaxLive, 0)
})
